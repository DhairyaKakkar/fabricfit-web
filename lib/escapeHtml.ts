// Escape user-supplied strings before interpolating them into HTML
// (e.g. transactional email bodies) to prevent HTML/markup injection.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
